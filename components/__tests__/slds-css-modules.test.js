/*
 * Equivalence check for the DSR-built SLDS 2 modules in css/
 * (scripts/build-slds-modules.ts, `npm run css:refresh`).
 *
 * The foundation plus every module, joined in manifest order, must reproduce
 * the installed `slds2.base.css` byte for byte (and the scoped build likewise),
 * so loading the modules cascades exactly like the monolith. A failure here
 * after `npm install` of a new SLDS version means css/ is stale: run
 * `npm run css:refresh`.
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync } from 'fs';
import { join } from 'path';
import postcss from 'postcss';

// Vitest runs from the repo root (jsdom has no file: import.meta.url).
const root = process.cwd();
const css = join(root, 'css');
const modular = join(
	root,
	'node_modules/@salesforce-ux/design-system-2/dist/css/modular'
);
const manifest = JSON.parse(readFileSync(join(css, 'manifest.json'), 'utf8'));
const components = JSON.parse(
	readFileSync(join(css, 'components.json'), 'utf8')
);
const installed = JSON.parse(
	readFileSync(
		join(root, 'node_modules/@salesforce-ux/design-system-2/package.json'),
		'utf8'
	)
).version;

const HEADER = '/*! Generated by @salesforce/design-system-react';
const stripHeader = (text) =>
	text.startsWith(HEADER) ? text.slice(text.indexOf('\n') + 1) : text;

const live = manifest.order.map((key) => manifest.modules[key]);

describe('css/ SLDS 2 modules', () => {
	it('were built from the installed SLDS version', () => {
		expect(manifest.source.version).toBe(installed);
	});

	for (const [label, dir, file] of [
		['unscoped', css, 'slds2.base.css'],
		['scoped', join(css, 'scoped'), 'slds2.scoped.base.css'],
	]) {
		it(`reassemble ${file} byte for byte (${label})`, () => {
			const rebuilt = live
				.map((mod) => stripHeader(readFileSync(join(dir, mod.path), 'utf8')))
				.join('');
			const base = readFileSync(join(modular, file), 'utf8');
			// Compare lengths first so a mismatch doesn't print 1 MB of CSS.
			expect(rebuilt.length).toBe(base.length);
			expect(rebuilt === base).toBe(true);
		});
	}

	it('parse as standalone stylesheets (no rule is split across files)', () => {
		for (const mod of live) {
			const text = readFileSync(join(css, mod.path), 'utf8');
			expect(() => postcss.parse(text), mod.path).not.toThrow();
		}
	});

	it('list every published module path in the manifest, including stubs', () => {
		for (const mod of Object.values(manifest.modules)) {
			expect(existsSync(join(css, mod.path)), mod.path).toBe(true);
			expect(existsSync(join(css, 'scoped', mod.path)), mod.path).toBe(true);
		}
	});

	it('have an entry file per component that imports its modules in cascade order', () => {
		expect(Object.keys(manifest.entries).sort()).toEqual(
			Object.keys(components).sort()
		);
		for (const [name, entry] of Object.entries(components)) {
			const text = readFileSync(join(css, `${name}.css`), 'utf8');
			const imports = [...text.matchAll(/@import '\.\/([^']+)';/g)].map(
				(m) => m[1]
			);
			const expected = ['foundation', ...entry.modules].map(
				(key) => manifest.modules[key].path
			);
			expect(imports, name).toEqual(expected);
			const positions = entry.modules.map((key) => manifest.order.indexOf(key));
			expect(positions, name).toEqual([...positions].sort((a, b) => a - b));
			for (const path of imports) {
				expect(existsSync(join(css, path)), path).toBe(true);
			}
		}
	});
});
