/*
 * Public API snapshot: the TypeScript declarations consumers get, committed
 * under `api/` so every type change shows up in the PR diff (like the story
 * HTML snapshots).
 *
 * Usage:
 *   tsx scripts/api-report.ts [--check | --update] [--root <dir>]
 *
 *   --check   (default) Fail if `api/` is stale, printing the diff.
 *   --update  Rewrite `api/` and delete orphaned files.
 *   --root    Project to snapshot (default: this repo). Used by the tests.
 *
 * Declarations are emitted with `tsc -p tsconfig.dts.json`, as `build:types`
 * does, into a temp dir. Every file under `components/` and `utilities/` is
 * public (the `exports` wildcards make each one importable) except those under
 * a `private/` folder. A private or `types/` file is included only when a
 * public file imports it, directly or transitively, since its declarations are
 * then part of the contract. Comments are stripped so doc edits aren't churn.
 *
 * Output: one `api/<dir>/<name>.api.d.ts` per component or utility folder (or
 * top-level file), with a section per declaration file.
 */
import { spawnSync } from 'child_process';
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from 'fs';
import { tmpdir } from 'os';
import { dirname, join, posix } from 'path';
import { fileURLToPath } from 'url';
import ts from 'typescript';
import {
	emitDeclarations,
	isPublic,
	reportFileOf,
	subpath,
	walk,
} from './api-declarations';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));

const args = process.argv.slice(2);
const update = args.includes('--update');
const rootArg = args.indexOf('--root');
const root = rootArg === -1 ? repoRoot : args[rootArg + 1];
const apiDir = join(root, 'api');
const { name: pkg } = JSON.parse(
	readFileSync(join(root, 'package.json'), 'utf8')
) as { name: string };

const HEADER =
	'// Generated by `npm run api:update` from the emitted declarations. Do not edit.\n';

/** Emit declarations; returns `relative path -> contents` for every `.d.ts`. */
const emit = (): Map<string, string> => {
	const out = mkdtempSync(join(tmpdir(), 'api-report-'));
	try {
		if (!emitDeclarations(root, out)) {
			// eslint-disable-next-line no-console
			console.error(
				'api-report: declaration emit failed; fix the type errors above.'
			);
			process.exit(1);
		}
		const files = new Map<string, string>();
		for (const file of walk(out).filter((f) => f.endsWith('.d.ts'))) {
			files.set(file, readFileSync(join(out, file), 'utf8'));
		}
		return files;
	} finally {
		rmSync(out, { recursive: true, force: true });
	}
};

/** Resolve a relative import specifier to an emitted `.d.ts` path. */
const resolveImport = (
	from: string,
	spec: string,
	files: Map<string, string>
): string | undefined => {
	if (!spec.startsWith('.')) return undefined;
	const base = posix.join(posix.dirname(from), spec).replace(/\.(m|c)?js$/, '');
	return [`${base}.d.ts`, `${base}/index.d.ts`].find((f) => files.has(f));
};

/** Public files plus every non-public file they reach through imports. */
const reachable = (files: Map<string, string>): Set<string> => {
	const seen = new Set<string>();
	const queue = [...files.keys()].filter(isPublic);
	while (queue.length) {
		const file = queue.pop()!;
		if (seen.has(file)) continue;
		seen.add(file);
		const { importedFiles } = ts.preProcessFile(files.get(file)!, true, true);
		for (const { fileName } of importedFiles) {
			const target = resolveImport(file, fileName, files);
			if (target && !seen.has(target)) queue.push(target);
		}
	}
	return seen;
};

const printer = ts.createPrinter({
	removeComments: true,
	newLine: ts.NewLineKind.LineFeed,
});
const normalize = (file: string, text: string): string =>
	printer
		.printFile(
			ts.createSourceFile(
				file,
				text,
				ts.ScriptTarget.Latest,
				false,
				ts.ScriptKind.TS
			)
		)
		.trimEnd();

const sectionTitle = (file: string): string =>
	isPublic(file)
		? `${pkg}/${subpath(file)}`
		: `${subpath(file)} (internal; referenced by public types)`;

const buildReport = (): Map<string, string> => {
	const files = emit();
	const groups = new Map<string, string[]>();
	for (const file of [...reachable(files)].sort()) {
		const sections = groups.get(reportFileOf(file)) ?? [];
		sections.push(
			`// ── ${sectionTitle(file)} ──\n${normalize(file, files.get(file)!)}\n`
		);
		groups.set(reportFileOf(file), sections);
	}
	const report = new Map<string, string>();
	for (const [file, sections] of groups) {
		report.set(file, HEADER + '\n' + sections.join('\n'));
	}
	return report;
};

const writeReport = (dir: string, report: Map<string, string>): void => {
	for (const [file, text] of report) {
		mkdirSync(dirname(join(dir, file)), { recursive: true });
		writeFileSync(join(dir, file), text);
	}
};

/* eslint-disable no-console */
const report = buildReport();

if (update) {
	rmSync(apiDir, { recursive: true, force: true });
	writeReport(apiDir, report);
	console.log(`api-report: wrote ${report.size} files to api/.`);
	process.exit(0);
}

const scratch = mkdtempSync(join(tmpdir(), 'api-report-expected-'));
try {
	writeReport(join(scratch, 'api'), report);
	if (!existsSync(apiDir)) mkdirSync(join(scratch, 'empty'));
	const diff = spawnSync(
		'git',
		[
			'diff',
			'--no-index',
			'--no-color',
			existsSync(apiDir) ? 'api' : join(scratch, 'empty'),
			join(scratch, 'api'),
		],
		{ cwd: root, encoding: 'utf8' }
	);
	if (diff.status === 0) {
		console.log(`api-report: api/ is up to date (${report.size} files).`);
	} else {
		console.error(
			diff.stdout.split(scratch).join('') +
				'\napi-report: the public API changed, so api/ is stale.\n' +
				'Run `npm run api:update`, review the diff, and commit it with your change.\n' +
				'If the change is breaking, use `!` and a `BREAKING CHANGE:` footer.'
		);
		process.exitCode = 1;
	}
} finally {
	rmSync(scratch, { recursive: true, force: true });
}
