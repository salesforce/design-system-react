/*
 * Split the published SLDS 2 stylesheet into per-component and per-utility
 * modules, so consumers can load only the CSS their components need.
 *
 * Usage:
 *   tsx scripts/build-slds-modules.ts [--dry-run] [--stub-removed]
 *                                     [--accept-unstyled] [--out <dir>]
 *                                     [--base-dir <dir>] [--source <dir>]
 *
 *   --dry-run          Print the module diff and size table; write nothing.
 *   --stub-removed     If a previously published module or entry path is gone,
 *                      write an empty stub for it instead of failing.
 *   --accept-unstyled  Allow classes DSR renders to stop resolving to a module.
 *   --out <dir>        Output directory (default: css/).
 *   --base-dir <dir>   Directory holding slds2.base.css and slds2.scoped.base.css
 *                      (default: the installed package's dist/css/modular).
 *   --source <dir>     A local checkout of packages/design-system-2. Its
 *                      src/**.css and import order replace the npm raw copies
 *                      as the selector index. The input is still base.css.
 *
 * How it works:
 *   1. Parse `slds2.base.css`. It is already compiled: nesting and `@for` are
 *      expanded and the `--` deprecated aliases are added.
 *   2. Index the class names in each raw source file that SLDS publishes
 *      (`dist/components/{name}/{name}.css`, `dist/components/utilities/*.css`).
 *   3. Assign every top-level node of base.css to the module whose index holds
 *      all its classes (falling back to the owner of its first class). Nodes
 *      with no class, such as `:root`, the layer-order line and the reset,
 *      belong to the run they sit in; everything before the first component
 *      rule is `slds2.foundation.css`.
 *   4. Cut base.css at run boundaries. Each module is a contiguous byte range,
 *      so the foundation plus every module in manifest order is base.css,
 *      byte for byte. The script fails if a module would need two separate
 *      ranges, because that order can't be reproduced by loading files.
 *   5. Write css/, css/scoped/ (from slds2.scoped.base.css), the manifest, the
 *      per-component entry files and css/components.json.
 *
 * `npm run css:refresh` runs this and then the equivalence and coverage tests.
 */
