// --- Selector helpers --------------------------------------------------------

const CLASS_RE = /\.(slds-[\w-]+)/g;
const PREFIX_ATTR_RE = /\[class[*^]=['"]?(slds-[\w-]+)['"]?\]/g;

/** Fold the `--` deprecated alias form onto the `_` form, for matching. */
const fold = (cls: string): string => cls.replace(/--/g, '_');

const classesIn = (selector: string): string[] => [
	...new Set([...selector.matchAll(CLASS_RE)].map((m) => m[1])),
];

/** Split a selector list on top-level commas (not those inside `:is(...)`). */
export const splitSelectors = (selector: string): string[] => {
	const parts: string[] = [];
	let depth = 0;
	let start = 0;
	for (let i = 0; i < selector.length; i += 1) {
		const ch = selector[i];
		if (ch === '(' || ch === '[') depth += 1;
		else if (ch === ')' || ch === ']') depth -= 1;
		else if (ch === ',' && depth === 0) {
			parts.push(selector.slice(start, i).trim());
			start = i + 1;
		}
	}
	parts.push(selector.slice(start).trim());
	return parts.filter(Boolean);
};

/**
 * Classes an element tree must carry for the selector to match: the classes
 * outside `:not/:is/:where/:has(...)` arguments, which are conditional.
 */
export const requiredClasses = (selector: string): string[] => {
	let out = '';
	let i = 0;
	while (i < selector.length) {
		const m = /^:(not|is|where|has)\(/.exec(selector.slice(i));
		if (m) {
			let depth = 0;
			let j = i + m[0].length - 1;
			for (; j < selector.length; j += 1) {
				if (selector[j] === '(') depth += 1;
				else if (selector[j] === ')') {
					depth -= 1;
					if (depth === 0) break;
				}
			}
			i = j + 1;
		} else {
			out += selector[i];
			i += 1;
		}
	}
	// `[class*='slds-table_column-']` requires some class with that prefix.
	const prefixes = [...out.matchAll(PREFIX_ATTR_RE)].map((m) => `${m[1]}*`);
	return [...classesIn(out), ...new Set(prefixes)];
};

/** Whether `classes` satisfies every required class or `prefix*` token. */
const satisfies = (req: string[], classes: Set<string>): boolean =>
	req.every((c) =>
		c.endsWith('*')
			? [...classes].some((have) => have.startsWith(c.slice(0, -1)))
			: classes.has(c)
	);

const selectorsOf = (node: ChildNode): string[] => {
	const list: string[] = [];
	if (node.type === 'rule') list.push(node.selector);
	else if (node.type === 'atrule')
		node.walkRules((r) => {
			list.push(r.selector);
		});
	return list;
};

// --- Raw-source index --------------------------------------------------------

interface RawModule {
	key: string;
	file: string;
	deprecated: boolean;
	classes: Set<string>;
	patterns: RegExp[];
	keyframes: Set<string>;
}

/** `button.deprecated.css` → `components/button`; utilities go under `utilities/`. */
const moduleKey = (stem: string, isUtility: boolean): string => {
	if (isUtility && stem === 'utilities.deprecated')
		return 'utilities/deprecated';
	const name = stem.replace(/\.deprecated$/, '');
	return `${isUtility ? 'utilities' : 'components'}/${name}`;
};

const indexRaw = (file: string, key: string, rel: string): RawModule => {
	const css = readFileSync(file, 'utf8');
	const classes = new Set<string>();
	const patterns: RegExp[] = [];
	const keyframes = new Set<string>();
	let parsed: Root;
	try {
		parsed = postcss.parse(css);
	} catch {
		// Raw sources use postcss-nested and postcss-for syntax; a file that
		// postcss can't parse is indexed by regex instead.
		parsed = postcss.parse('');
		for (const m of css.matchAll(/\.(slds-[\w$()-]+)/g)) classes.add(m[1]);
	}
	parsed.walkRules((rule) => {
		for (const m of rule.selector.matchAll(/\.(slds-[\w$()-]+)/g)) {
			classes.add(m[1]);
		}
	});
	parsed.walkAtRules('keyframes', (a) => {
		keyframes.add(a.params);
	});
	for (const cls of [...classes]) {
		if (cls.includes('$(')) {
			// `@for` interpolation, e.g. `slds-table_column-$(i)-wrap`.
			classes.delete(cls);
			const re = cls
				.split(/\$\([\w-]+\)/)
				.map((s) => s.replace(/[-]/g, '\\-'))
				.join('\\d+');
			patterns.push(new RegExp(`^${fold(re)}$`));
		}
	}
	return {
		key,
		file: rel,
		deprecated: /\.deprecated\.css$/.test(file),
		classes: new Set([...classes].map(fold)),
		patterns,
		keyframes,
	};
};

const listCss = (dir: string): string[] =>
	readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) {
			if (entry.name === 'themes' || entry.name.startsWith('__')) return [];
			return listCss(full);
		}
		return entry.name.endsWith('.css') ? [full] : [];
	});

/** Index the npm package's raw copies, or a local SLDS source checkout. */
export const buildRawIndex = (source?: string): RawModule[] => {
	if (source) {
		const files = [
			...listCss(join(source, 'src/slds2')),
			...listCss(join(source, 'src/sub-themes')),
		];
		const order = readImportOrder(source);
		const stemOf = (f: string) =>
			f
				.split('/')
				.pop()!
				.replace(/\.css$/, '');
		files.sort(
			(a, b) =>
				(order.indexOf(stemOf(a)) + 1 || 1e6) -
				(order.indexOf(stemOf(b)) + 1 || 1e6)
		);
		return files.map((f) =>
			indexRaw(
				f,
				moduleKey(stemOf(f), f.includes('/utilities/')),
				relative(source, f)
			)
		);
	}
	const base = join(PKG_DIR, 'dist/components');
	return listCss(base)
		.sort()
		.map((f) => {
			const rel = relative(base, f);
			const stem = rel
				.split('/')
				.pop()!
				.replace(/\.css$/, '');
			return indexRaw(
				f,
				moduleKey(stem, rel.startsWith('utilities/')),
				`dist/components/${rel}`
			);
		});
};

/** The quoted entries of `scripts/buildCss/import-order.ts` in a source checkout. */
const readImportOrder = (source: string): string[] => {
	const file = join(source, 'scripts/buildCss/import-order.ts');
	if (!existsSync(file)) return [];
	return [...readFileSync(file, 'utf8').matchAll(/^\s*'([\w.-]+)',/gm)].map(
		(m) => m[1]
	);
};

// --- Partition ---------------------------------------------------------------

export interface Run {
	key: string;
	start: number;
	end: number;
}

const ownerOf = (raw: RawModule[], cls: string): RawModule[] =>
	raw.filter(
		(m) => m.classes.has(cls) || m.patterns.some((re) => re.test(cls))
	);

/** Candidate module keys per node, or `null` for nodes with no class. */
const candidatesFor = (node: ChildNode, raw: RawModule[]): string[] | null => {
	if (node.type === 'atrule' && node.name === 'keyframes') {
		const keys = raw
			.filter((m) => m.keyframes.has(node.params))
			.map((m) => m.key);
		return keys.length ? [...new Set(keys)] : null;
	}
	const classes = [...new Set(selectorsOf(node).flatMap(classesIn))].map(fold);
	if (!classes.length) return null;
	const all = raw.filter((m) =>
		classes.every(
			(c) => m.classes.has(c) || m.patterns.some((re) => re.test(c))
		)
	);
	const pool = all.length ? all : ownerOf(raw, classes[0]);
	if (pool.length) return [...new Set(pool.map((m) => m.key))];
	const extra = classes.map((c) => EXTRA_OWNERS[c]).find(Boolean);
	return extra ? [extra] : null;
};

/**
 * Assign every top-level node to a module. Greedy: at each module start, take
 * the candidate whose run reaches furthest. Nodes with no class join the run
 * they're in; leading ones form the foundation.
 */
export const partition = (base: Root, raw: RawModule[]): Run[] => {
	const nodes = base.nodes;
	const cands = nodes.map((n) => candidatesFor(n, raw));
	const runs: Run[] = [];
	const first = cands.findIndex((c) => c !== null);
	runs.push({ key: 'foundation', start: 0, end: first });
	let i = first;
	while (i < nodes.length) {
		let best = '';
		let bestEnd = -1;
		for (const key of cands[i]!) {
			let k = i;
			while (k < nodes.length && (cands[k] === null || cands[k]!.includes(key)))
				k += 1;
			if (k > bestEnd) {
				best = key;
				bestEnd = k;
			}
		}
		const prev = runs[runs.length - 1];
		if (prev.key === best) prev.end = bestEnd;
		else runs.push({ key: best, start: i, end: bestEnd });
		i = bestEnd;
	}
	const seen = new Set<string>();
	for (const run of runs) {
		if (seen.has(run.key)) {
			throw new Error(
				`Module ${run.key} needs more than one range of base.css. Loading ` +
					'modules as files could not reproduce the monolith order.'
			);
		}
		seen.add(run.key);
	}
	return runs;
};

/** Cut `css` at the start offsets of each run's first node. */
const sliceText = (css: string, base: Root, runs: Run[]): string[] =>
	runs.map((run, idx) => {
		const from = idx === 0 ? 0 : base.nodes[run.start].source!.start!.offset;
		const next = runs[idx + 1];
		const to = next ? base.nodes[next.start].source!.start!.offset : css.length;
		return css.slice(from, to);
	});

// --- Class index of the output ----------------------------------------------

interface ModuleClasses {
	key: string;
	classes: Set<string>;
	prefixes: string[];
	selectors: string[][];
}

const moduleClasses = (base: Root, runs: Run[]): ModuleClasses[] =>
	runs.map((run) => {
		const classes = new Set<string>();
		const prefixes: string[] = [];
		const selectors: string[][] = [];
		for (const node of base.nodes.slice(run.start, run.end)) {
			for (const sel of selectorsOf(node)) {
				classesIn(sel).forEach((c) => classes.add(c));
				for (const m of sel.matchAll(PREFIX_ATTR_RE)) prefixes.push(m[1]);
				for (const one of splitSelectors(sel)) {
					const req = requiredClasses(one);
					if (req.length) selectors.push(req);
				}
			}
		}
		return { key: run.key, classes, prefixes, selectors };
	});

/** The modules whose rules mention `cls` (directly or by `[class^=]`). */
const modulesMentioning = (index: ModuleClasses[], cls: string): string[] =>
	index
		.filter(
			(m) => m.classes.has(cls) || m.prefixes.some((p) => cls.startsWith(p))
		)
		.map((m) => m.key);

/**
 * The module that defines `cls`: the first whose selectors use it with the
 * fewest other required classes (`.slds-truncate` alone beats
 * `.slds-table .slds-truncate`). `[class^=]` prefix matches count last.
 */
const STATE_RE = /^slds-(is|has)-/;

const squash = (s: string): string => s.toLowerCase().replace(/[^a-z]/g, '');

const homeOf = (index: ModuleClasses[], cls: string): string | undefined => {
	// On a tie, the module named after the class's block wins
	// (`slds-popover__footer` → popover, not colorPicker, which also styles it).
	const block = squash(cls.replace(/^slds-/, '').split(/_/)[0]);
	let best: string | undefined;
	let bestSize = Infinity;
	let bestNamed = false;
	for (const m of index) {
		const named = squash(m.key.split('/')[1] ?? '') === block;
		for (const req of m.selectors) {
			if (!req.includes(cls)) continue;
			if (
				req.length < bestSize ||
				(req.length === bestSize && named && !bestNamed)
			) {
				best = m.key;
				bestSize = req.length;
				bestNamed = named;
			}
		}
	}
	return (
		best ??
		index.find(
			(m) => m.classes.has(cls) || m.prefixes.some((p) => cls.startsWith(p))
		)?.key
	);
};

// --- DSR component class sets ------------------------------------------------

const SOURCE_EXT = ['.tsx', '.ts', '.jsx', '.js'];
const SKIP_DIRS = new Set(['__tests__', '__docs__', '__examples__']);

const sourceFiles = (dir: string): string[] =>
	readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const full = join(dir, entry.name);
		if (entry.isDirectory())
			return SKIP_DIRS.has(entry.name) ? [] : sourceFiles(full);
		return SOURCE_EXT.some((e) => entry.name.endsWith(e)) &&
			!entry.name.endsWith('.d.ts')
			? [full]
			: [];
	});

const resolveImport = (from: string, spec: string): string | undefined => {
	const target = resolve(dirname(from), spec);
	for (const candidate of [
		...SOURCE_EXT.map((e) => target + e),
		...SOURCE_EXT.map((e) => join(target, `index${e}`)),
	]) {
		if (existsSync(candidate)) return candidate;
	}
	return undefined;
};

/** Every `slds-*` literal in a component's source and the components it imports. */
const sourceClasses = (componentDir: string): Set<string> => {
	const componentsRoot = join(root, 'components');
	const seen = new Set<string>();
	const classes = new Set<string>();
	const queue = sourceFiles(componentDir);
	while (queue.length) {
		const file = queue.pop()!;
		if (seen.has(file)) continue;
		seen.add(file);
		const text = readFileSync(file, 'utf8');
		for (const m of text.matchAll(
			/(?<!-)\bslds-[\w-]*[a-zA-Z0-9]\b(?![-_$])/g
		)) {
			classes.add(m[0]);
		}
		for (const m of text.matchAll(/from\s+'(\.[^']+)'/g)) {
			const dep = resolveImport(file, m[1]);
			if (dep && dep.startsWith(componentsRoot) && !dep.includes('/__'))
				queue.push(dep);
		}
	}
	return classes;
};

const SNAP = join(
	root,
	'components/__tests__/__snapshots__/story-snapshots.test.jsx.snap'
);

/** `slds-*` classes in each story file's snapshots, keyed by story file name. */
const snapshotClasses = (): Map<string, Set<string>> => {
	const out = new Map<string, Set<string>>();
	const text = readFileSync(SNAP, 'utf8');
	const re =
		/^exports\[`Story HTML snapshots > (.+?) > .*?`\] = `([\s\S]*?)`;$/gm;
	for (const m of text.matchAll(re)) {
		const set = out.get(m[1]) ?? new Set<string>();
		for (const attr of m[2].matchAll(/class="([^"]*)"/g)) {
			attr[1]
				.split(/\s+/)
				.filter((c) => c.startsWith('slds-'))
				.forEach((c) => set.add(c));
		}
		out.set(m[1], set);
	}
	return out;
};

/** Component dir → story file names (`Combobox`, `SearchInput`, ...). */
const storyNames = (): Map<string, string[]> => {
	const out = new Map<string, string[]>();
	const walk = (dir: string) => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const full = join(dir, entry.name);
			if (entry.isDirectory()) walk(full);
			else {
				const m = /^(.+)\.stories\.[jt]sx$/.exec(entry.name);
				const comp = /components\/([^/]+)\//.exec(full);
				if (m && comp && full.includes('/__docs__/')) {
					out.set(comp[1], [...(out.get(comp[1]) ?? []), m[1]]);
				}
			}
		}
	};
	walk(join(root, 'components'));
	return out;
};

export interface ComponentEntry {
	modules: string[];
	unstyled: string[];
}

const componentMap = (
	index: ModuleClasses[],
	order: string[]
): Record<string, ComponentEntry> => {
	const snaps = snapshotClasses();
	const stories = storyNames();
	const out: Record<string, ComponentEntry> = {};
	const dirs = readdirSync(join(root, 'components'), { withFileTypes: true })
		.filter(
			(d) =>
				d.isDirectory() &&
				SOURCE_EXT.some((e) =>
					existsSync(join(root, 'components', d.name, `index${e}`))
				)
		)
		.map((d) => d.name)
		.sort();
	for (const dir of dirs) {
		const classes = sourceClasses(join(root, 'components', dir));
		for (const story of stories.get(dir) ?? []) {
			snaps.get(story)?.forEach((c) => classes.add(c));
		}
		if (!classes.size) continue;
		const modules = new Set<string>();
		const unstyled: string[] = [];
		for (const cls of classes) {
			// State classes (`slds-is-open`, `slds-has-error`) only style something
			// in combination, which the selector check below covers.
			if (STATE_RE.test(cls)) {
				if (!index.some((m) => m.classes.has(cls))) unstyled.push(cls);
				continue;
			}
			const home = homeOf(index, cls);
			if (home) modules.add(home);
			else unstyled.push(cls);
		}
		for (const m of index) {
			if (m.selectors.some((req) => satisfies(req, classes)))
				modules.add(m.key);
		}
		modules.delete('foundation');
		out[dir] = {
			modules: order.filter((k) => modules.has(k)),
			unstyled: unstyled.sort(),
		};
	}
	return out;
};

